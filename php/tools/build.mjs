// Generates the PHP port's data files from the Node sources of truth:
//   php/app/data/models.json   data model (also served in /api/me)
//   php/app/data/roles.json    role -> apps + dashboard widgets
//   php/app/data/schema.sql    MySQL / MariaDB schema
//   php/app/data/seed.json     demo data (exact output of server/seed.js, password hashes stripped)
// Run from the repo root:  node php/tools/build.mjs
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const out = path.join(root, 'php', 'app', 'data');
fs.mkdirSync(out, { recursive: true });

// Seed into a throwaway working directory so the local JSON store never touches the repo's data/.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'prostars-seed-'));
process.chdir(tmp);
const url = p => pathToFileURL(path.join(root, p)).href;
const { models } = await import(url('server/models.js'));
const { ROLES } = await import(url('server/roles.js'));
const { seedIfEmpty } = await import(url('server/seed.js'));

fs.writeFileSync(path.join(out, 'models.json'), JSON.stringify(models));
fs.writeFileSync(path.join(out, 'roles.json'), JSON.stringify(ROLES));

// ---- MySQL schema ----
const SQL = { text: 'VARCHAR(191)', select: 'VARCHAR(191)', ref: 'VARCHAR(191)', longtext: 'TEXT', number: 'DECIMAL(18,4)',
  date: 'DATE', datetime: 'DATETIME(3)', bool: 'TINYINT(1)', json: 'JSON' };
// 'id' is CHAR(36); _row preserves insertion order (list() order); created_at/updated_at are UTC DATETIME(3).
const INDEXED = new Set(['status', 'key', 'run_id', 'client_id', 'employee_id', 'project_id', 'po_id', 'ticket_id']);
let sql = '-- Generated by php/tools/build.mjs from server/models.js. Do not edit by hand.\nSET NAMES utf8mb4;\n\n';
for (const [table, m] of Object.entries(models)) {
  const cols = ['  `id` CHAR(36) NOT NULL', '  `_row` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT', '  `created_at` DATETIME(3) NULL', '  `updated_at` DATETIME(3) NULL',
    ...Object.entries(m.fields).map(([k, f]) => `  \`${k}\` ${SQL[f.type] || 'VARCHAR(191)'} NULL`)];
  const idx = ['  PRIMARY KEY (`id`)', '  UNIQUE KEY `_row_idx` (`_row`)', '  KEY `updated_at_idx` (`updated_at`)',
    ...Object.entries(m.fields).filter(([k, f]) => f.type === 'ref' || INDEXED.has(k)).map(([k]) => `  KEY \`${k}_idx\` (\`${k}\`)`)];
  sql += `CREATE TABLE IF NOT EXISTS \`${table}\` (\n${[...cols, ...idx].join(',\n')}\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;\n\n`;
}
// Document-number counters (concurrency-safe replacement for the Node "max + 1" scan).
sql += 'CREATE TABLE IF NOT EXISTS `_counters` (\n  `name` VARCHAR(100) NOT NULL,\n  `n` BIGINT UNSIGNED NOT NULL DEFAULT 0,\n  PRIMARY KEY (`name`)\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n';
fs.writeFileSync(path.join(out, 'schema.sql'), sql);

// ---- demo data ----
process.env.SEED_PASSWORD = 'unused';
await seedIfEmpty();
await new Promise(r => setTimeout(r, 600)); // local store saves on a 150 ms debounce
const data = JSON.parse(fs.readFileSync(path.join(tmp, 'data', 'db.json'), 'utf8'));
for (const u of data.users || []) delete u.password_hash; // install.php sets real hashes with password_hash()
fs.writeFileSync(path.join(out, 'seed.json'), JSON.stringify(data));
process.chdir(root);
fs.rmSync(tmp, { recursive: true, force: true });
const counts = Object.entries(data).map(([t, r]) => `${t}:${r.length}`).join(' ');
console.log(`models: ${Object.keys(models).length} tables, roles: ${Object.keys(ROLES).length}\nseed rows -> ${counts}`);
