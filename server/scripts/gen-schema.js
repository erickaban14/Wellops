import fs from 'node:fs';
import { fullSchema } from '../schema.js';

const sql = `-- ProStars ERP schema for Supabase. Generated by \`npm run schema\` from server/models.js - do not edit by hand.
-- Run this in the Supabase SQL editor (safe to re-run after upgrades).

${fullSchema({ rls: true })}
-- Storage bucket for manuals / API documents (private; the server issues signed URLs).
insert into storage.buckets (id, name, public) values ('manuals', 'manuals', false) on conflict (id) do nothing;
`;
fs.mkdirSync('supabase', { recursive: true });
fs.writeFileSync('supabase/schema.sql', sql);
console.log('Wrote supabase/schema.sql');
